"""PDF report card matching the on-screen SchoolReportTranscript preview."""

from __future__ import annotations

import io
import re
from typing import Any

from reportlab.lib import colors
from reportlab.lib.enums import TA_CENTER, TA_LEFT
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import (
    HRFlowable,
    Paragraph,
    SimpleDocTemplate,
    Spacer,
    Table,
    TableStyle,
)

BLUE = colors.HexColor("#1a85d6")
INK = colors.HexColor("#0f172a")
MUTED = colors.HexColor("#64748b")
BORDER = colors.HexColor("#e2e8f0")
PANEL = colors.HexColor("#f8fafc")


def _safe(text: Any) -> str:
    raw = str(text or "").replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    return raw


def _pct(value: Any) -> str:
    try:
        return f"{float(value):.0f}%"
    except (TypeError, ValueError):
        return "—"


def _num(value: Any, digits: int = 0) -> str:
    try:
        n = float(value)
        return f"{n:.{digits}f}" if digits else f"{n:.0f}"
    except (TypeError, ValueError):
        return "—"


def transcript_pdf_filename(transcript: dict) -> str:
    student = (transcript.get("student") or {}).get("full_name") or "student"
    fy = transcript.get("fy") or "report"
    slug = re.sub(r"[^A-Za-z0-9]+", "_", student).strip("_") or "student"
    fy_slug = re.sub(r"[^A-Za-z0-9]+", "_", fy).strip("_")
    return f"ZenK_Transcript_{slug}_{fy_slug}.pdf"


def generate_transcript_pdf(transcript: dict) -> bytes:
    """Build a branded multi-section PDF from the same transcript dict as preview."""
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        leftMargin=16 * mm,
        rightMargin=16 * mm,
        topMargin=14 * mm,
        bottomMargin=14 * mm,
        title="ZenK Student Progress Transcript",
    )

    styles = getSampleStyleSheet()
    title = ParagraphStyle(
        "ZenkTitle",
        parent=styles["Heading1"],
        fontSize=16,
        textColor=INK,
        spaceAfter=2,
        leading=20,
    )
    kicker = ParagraphStyle(
        "ZenkKicker",
        parent=styles["Normal"],
        fontSize=9,
        textColor=BLUE,
        spaceAfter=8,
        fontName="Helvetica-Bold",
    )
    h2 = ParagraphStyle(
        "ZenkH2",
        parent=styles["Heading2"],
        fontSize=11,
        textColor=INK,
        spaceBefore=10,
        spaceAfter=6,
    )
    body = ParagraphStyle(
        "ZenkBody",
        parent=styles["Normal"],
        fontSize=9.5,
        textColor=INK,
        leading=13,
    )
    muted = ParagraphStyle(
        "ZenkMuted",
        parent=styles["Normal"],
        fontSize=8.5,
        textColor=MUTED,
        leading=11,
    )
    center = ParagraphStyle(
        "ZenkCenter",
        parent=body,
        alignment=TA_CENTER,
    )

    student = transcript.get("student") or {}
    metrics = transcript.get("metrics") or {}
    story: list = []

    story.append(Paragraph("Official progress transcript", kicker))
    story.append(Paragraph(_safe(transcript.get("school_name") or "School"), title))
    story.append(
        Paragraph(
            f"FY {_safe(transcript.get('fy') or '—')} · Generated by ZenK Impact",
            muted,
        )
    )
    story.append(Spacer(1, 6))
    story.append(HRFlowable(width="100%", thickness=1, color=BORDER, spaceAfter=10))

    story.append(Paragraph(_safe(student.get("full_name") or "Student"), title))
    meta_bits = [
        f"Grade {_safe(student.get('grade') or '—')}",
        f"Circle {_safe(student.get('circle_name') or 'Unassigned')}",
        f"Teacher {_safe(student.get('class_teacher') or '—')}",
        f"Sponsor Lead {_safe(student.get('sponsor_lead') or '—')}",
    ]
    if student.get("mentor_name"):
        meta_bits.append(f"Mentor {_safe(student.get('mentor_name'))}")
    story.append(Paragraph(" · ".join(meta_bits), muted))
    status = "Finalized" if transcript.get("finalized") else "Draft"
    story.append(Paragraph(f"Status: <b>{status}</b>", body))
    story.append(Spacer(1, 8))

    story.append(Paragraph("Key metrics", h2))
    metric_rows = [
        [
            Paragraph("<b>Attendance</b>", center),
            Paragraph("<b>Avg score</b>", center),
            Paragraph("<b>ZQA</b>", center),
            Paragraph("<b>Class rank</b>", center),
            Paragraph("<b>Risk</b>", center),
        ],
        [
            Paragraph(_pct(metrics.get("attendance_pct")), center),
            Paragraph(_pct(metrics.get("avg_score")), center),
            Paragraph(
                _pct(metrics.get("zqa_score")) if float(metrics.get("zqa_score") or 0) > 0 else "—",
                center,
            ),
            Paragraph(
                f"{_safe(metrics.get('rank_in_class') or '—')} / {_safe(metrics.get('class_size') or '—')}",
                center,
            ),
            Paragraph(_safe(metrics.get("risk_level") or "—"), center),
        ],
    ]
    metrics_table = Table(metric_rows, colWidths=[32 * mm, 32 * mm, 28 * mm, 40 * mm, 28 * mm])
    metrics_table.setStyle(
        TableStyle(
            [
                ("BACKGROUND", (0, 0), (-1, -1), PANEL),
                ("BOX", (0, 0), (-1, -1), 0.6, BORDER),
                ("INNERGRID", (0, 0), (-1, -1), 0.4, BORDER),
                ("TOPPADDING", (0, 0), (-1, -1), 8),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 8),
            ]
        )
    )
    story.append(metrics_table)

    subjects_by_quarter = transcript.get("subjects_by_quarter") or {}
    if subjects_by_quarter:
        story.append(Paragraph("Subject performance", h2))
        for quarter, rows in sorted(subjects_by_quarter.items()):
            story.append(Paragraph(f"<b>{_safe(quarter)}</b>", body))
            data = [[Paragraph("<b>Subject</b>", body), Paragraph("<b>Score</b>", body)]]
            for row in rows:
                data.append(
                    [
                        Paragraph(_safe(row.get("subject")), body),
                        Paragraph(_pct(row.get("score")), body),
                    ]
                )
            t = Table(data, colWidths=[120 * mm, 40 * mm])
            t.setStyle(
                TableStyle(
                    [
                        ("BACKGROUND", (0, 0), (-1, 0), PANEL),
                        ("BOX", (0, 0), (-1, -1), 0.5, BORDER),
                        ("INNERGRID", (0, 0), (-1, -1), 0.4, BORDER),
                        ("TOPPADDING", (0, 0), (-1, -1), 5),
                        ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
                    ]
                )
            )
            story.append(t)
            story.append(Spacer(1, 6))

    blooms = transcript.get("blooms")
    sel = transcript.get("sel")
    if blooms or sel:
        story.append(Paragraph("Learning & wellbeing", h2))
        split: list = []
        if blooms:
            bloom_data = [
                [Paragraph("<b>Bloom's taxonomy</b>", body), Paragraph(f"<b>{_safe(blooms.get('quarter') or '')}</b>", body)],
                [Paragraph("Remember", muted), Paragraph(_num(blooms.get("remember")), body)],
                [Paragraph("Understand", muted), Paragraph(_num(blooms.get("understand")), body)],
                [Paragraph("Apply", muted), Paragraph(_num(blooms.get("apply")), body)],
                [Paragraph("Analyse", muted), Paragraph(_num(blooms.get("analyse")), body)],
                [Paragraph("Evaluate", muted), Paragraph(_num(blooms.get("evaluate")), body)],
                [Paragraph("Create", muted), Paragraph(_num(blooms.get("create")), body)],
            ]
            bt = Table(bloom_data, colWidths=[45 * mm, 25 * mm])
            bt.setStyle(
                TableStyle(
                    [
                        ("BOX", (0, 0), (-1, -1), 0.5, BORDER),
                        ("BACKGROUND", (0, 0), (-1, 0), PANEL),
                        ("TOPPADDING", (0, 0), (-1, -1), 4),
                        ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
                    ]
                )
            )
            split.append(bt)
        if sel:
            sel_data = [
                [Paragraph("<b>SEL dimensions</b>", body), Paragraph(f"<b>{_safe(sel.get('quarter') or '')}</b>", body)],
                [Paragraph("Self-awareness", muted), Paragraph(_num(sel.get("self_awareness")), body)],
                [Paragraph("Self-management", muted), Paragraph(_num(sel.get("self_management")), body)],
                [Paragraph("Social awareness", muted), Paragraph(_num(sel.get("social_awareness")), body)],
                [Paragraph("Relationship skills", muted), Paragraph(_num(sel.get("relationship_skills")), body)],
                [Paragraph("Responsible decisions", muted), Paragraph(_num(sel.get("responsible_decisions")), body)],
            ]
            st = Table(sel_data, colWidths=[50 * mm, 25 * mm])
            st.setStyle(
                TableStyle(
                    [
                        ("BOX", (0, 0), (-1, -1), 0.5, BORDER),
                        ("BACKGROUND", (0, 0), (-1, 0), PANEL),
                        ("TOPPADDING", (0, 0), (-1, -1), 4),
                        ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
                    ]
                )
            )
            split.append(st)
        if len(split) == 2:
            wrap = Table([[split[0], split[1]]], colWidths=[80 * mm, 80 * mm])
            wrap.setStyle(TableStyle([("VALIGN", (0, 0), (-1, -1), "TOP"), ("LEFTPADDING", (1, 0), (1, 0), 10)]))
            story.append(wrap)
        else:
            story.append(split[0])

    narrative = transcript.get("narrative") or {}
    if narrative.get("narrative"):
        story.append(Paragraph("Teacher narrative", h2))
        head = " · ".join(
            x
            for x in [
                narrative.get("quarter"),
                narrative.get("teacher_name"),
            ]
            if x
        )
        if head:
            story.append(Paragraph(_safe(head), muted))
        story.append(Paragraph(_safe(narrative.get("narrative")), body))

    story.append(Spacer(1, 14))
    story.append(HRFlowable(width="100%", thickness=0.6, color=BORDER, spaceAfter=6))
    story.append(
        Paragraph(
            "This official ZenK transcript was distributed by the school. "
            "Please keep it for circle records.",
            muted,
        )
    )

    doc.build(story)
    return buffer.getvalue()
